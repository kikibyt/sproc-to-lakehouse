"""Generate a Databricks notebook (``.py`` source format) from a conversion plan.

One cell per step. SQL runs through ``spark.sql(query, args=...)`` with named parameter
markers, so parameter values are never pasted into SQL text. Manual steps get a
markdown cell with the reasons and the original T-SQL, followed by a cell that raises,
so a partly converted notebook cannot silently run to completion.
"""

from __future__ import annotations

import keyword

from sproc_to_lakehouse.codegen.plan import Plan, Step, StepKind
from sproc_to_lakehouse.codegen.render import SqlRenderer, params_used, scalars_used
from sproc_to_lakehouse.codegen.variables import ParamInfo
from sproc_to_lakehouse.models import Severity

CELL = "\n\n# COMMAND ----------\n\n"
HEADER = "# Databricks notebook source\n"


def py_name(name: str) -> str:
    return f"{name}_" if keyword.iskeyword(name) else name


def scalar_name(name: str) -> str:
    return f"v_{name}"


def _markdown(lines: list[str]) -> str:
    return "\n".join(f"# MAGIC {line}".rstrip() for line in ["%md", *lines])


def _renderer() -> SqlRenderer:
    return SqlRenderer(
        table=lambda ref: ref.qualified_name,
        param=lambda name: f":{name}",
        scalar=lambda name: f":{scalar_name(name)}",
    )


def generate_notebook(plan: Plan) -> str:
    renderer = _renderer()
    cells = [_intro(plan), _widgets(plan)]
    for number, step in enumerate(plan.steps, start=1):
        cells.extend(_step_cells(number, step, renderer))
    if plan.is_fully_converted:
        cells.append(_markdown([f"Done: `{plan.name}` converted without manual steps."]))
    return HEADER + CELL.join(c for c in cells if c) + "\n"


def _intro(plan: Plan) -> str:
    proc = plan.analysis.procedure
    manual = len(plan.manual_steps)
    status = (
        "**Status:** fully converted."
        if manual == 0
        else f"**Status:** {manual} step(s) need manual conversion; "
        "the notebook stops at the first one."
    )
    lines = [
        f"# {proc.name}",
        "",
        f"Generated by sproc-to-lakehouse from T-SQL procedure `{proc.qualified_name}`"
        + (f" (`{proc.source_path}`)." if proc.source_path else "."),
        "",
        status,
    ]
    notes = plan.analysis.by_severity(Severity.AUTO_WITH_NOTE)
    if notes:
        lines += ["", "**Review notes** (converted, but semantics differ slightly):", ""]
        seen: set[str] = set()
        for f in notes:
            if f.rule_id not in seen:
                seen.add(f.rule_id)
                lines.append(f"- `{f.rule_id}` {f.message}")
    if plan.dropped:
        lines += ["", "**Dropped** (no Databricks equivalent needed):", ""]
        lines += [f"- line {d.line}: {d.reason}" for d in plan.dropped]
    return _markdown(lines)


def _widget_default(info: ParamInfo) -> str:
    default = (info.default or "").strip()
    if not default or default.upper() == "NULL":
        return ""
    if default[:1] in "Nn" and default[1:2] == "'":
        default = default[1:]
    return default.strip("'").replace("''", "'")


def _widgets(plan: Plan) -> str:
    params = [p for p in plan.env.params.values()]
    if not params:
        return ""
    lines = ["# Parameters (empty text = NULL, as in the T-SQL procedure)"]
    for info in params:
        widget = f'dbutils.widgets.text("{info.name}", "{_widget_default(info)}")'
        lines.append(f"{widget}  # T-SQL type: {info.tsql_type}")
    lines.append("")
    for info in params:
        lines.append(f'{py_name(info.name)} = dbutils.widgets.get("{info.name}") or None')
    return "\n".join(lines)


def _args(step: Step) -> str:
    pairs = [f'"{n}": {py_name(n)}' for n in sorted(params_used(step.sql))]
    pairs += [f'"{scalar_name(n)}": {scalar_name(n)}' for n in sorted(scalars_used(step.sql))]
    return "{" + ", ".join(pairs) + "}"


def _spark_sql(step: Step, renderer: SqlRenderer) -> str:
    sql = renderer.render(step.sql)
    return f'spark.sql(r"""\n{sql}\n""", args={_args(step)})'


def _step_cells(number: int, step: Step, renderer: SqlRenderer) -> list[str]:
    title = f"### Step {number}: {step.title} (T-SQL line {step.line})"
    if step.kind is StepKind.MANUAL:
        lines = [title, "", "**Manual conversion required.**", ""]
        lines += [f"- {reason}" for reason in step.reasons]
        lines += ["", "Original T-SQL:", "", "```sql", *step.source_sql.splitlines(), "```"]
        code = (
            f'raise NotImplementedError("Step {number} (T-SQL line {step.line}) needs manual '
            'conversion; see the notes in the cell above.")'
        )
        return [_markdown(lines), code]

    header = [title]
    if step.rewrites:
        header.append(f"Rewrites applied: {', '.join(sorted(step.rewrites))}.")
    md = _markdown(header)
    if step.kind is StepKind.PRINT:
        text = step.sql.this if step.sql is not None else step.source_sql
        return [md, f"print({text!r})"]
    if step.kind is StepKind.SCALAR:
        return [md, f'{scalar_name(step.name)} = {_spark_sql(step, renderer)}.first()["value"]']
    if step.kind is StepKind.TEMP_VIEW:
        return [md, f'{_spark_sql(step, renderer)}.createOrReplaceTempView("{step.name}")']
    if step.kind is StepKind.RESULT:
        return [md, f"display({_spark_sql(step, renderer)})"]
    return [md, f"{_spark_sql(step, renderer)}"]
