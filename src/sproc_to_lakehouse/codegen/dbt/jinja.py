"""Small helpers for emitting dbt Jinja."""

from __future__ import annotations

import json
import re

from sproc_to_lakehouse.codegen.variables import ParamInfo

_JINJA_EXPR_RE = re.compile(r"\{\{\s*(.*?)\s*\}\}", re.S)

# Renders a Python/agate value as a SQL literal. Used for dbt vars (always strings or
# None from the CLI) and for values fetched with run_query.
SQL_LITERAL_MACRO = """\
{#- Render a value as a SQL literal: NULL, number, DATE/TIMESTAMP or quoted string.
    Generated by sproc-to-lakehouse. -#}
{% macro sql_literal(value) -%}
  {%- if value is none -%}NULL
  {%- elif value is boolean -%}{{ 'TRUE' if value else 'FALSE' }}
  {%- elif value is number -%}{{ value }}
  {%- elif value.hour is defined -%}TIMESTAMP '{{ value.isoformat(sep=" ") }}'
  {%- elif value.year is defined -%}DATE '{{ value.isoformat() }}'
  {%- else -%}'{{ value | string | replace("'", "''") }}'
  {%- endif -%}
{%- endmacro %}
"""


def var_default(info: ParamInfo) -> str | None:
    """The Jinja literal for a parameter's T-SQL default, or None if it has none."""
    default = (info.default or "").strip()
    if not default:
        return None
    if default.upper() == "NULL":
        return "none"
    if re.fullmatch(r"-?\d+(\.\d+)?", default):
        return default
    if default[:1] in "Nn" and default[1:2] == "'":
        default = default[1:]
    if default.startswith("'") and default.endswith("'"):
        return json.dumps(default[1:-1].replace("''", "'"))
    return None  # expression defaults (rare) are left required


def param_expression(info: ParamInfo) -> str:
    default = var_default(info)
    lookup = f"var('{info.name}', {default})" if default is not None else f"var('{info.name}')"
    return f"{{{{ sql_literal({lookup}) }}}}"


def as_jinja_string(text: str) -> str:
    """Turn template text containing ``{{ expr }}`` into one Jinja string expression,
    for use inside ``config(...)`` arguments: ``"a = " ~ (expr) ~ ""``."""
    parts: list[str] = []
    pos = 0
    for match in _JINJA_EXPR_RE.finditer(text):
        if match.start() > pos:
            parts.append(json.dumps(text[pos : match.start()]))
        parts.append(f"({match.group(1)})")
        pos = match.end()
    if pos < len(text):
        parts.append(json.dumps(text[pos:]))
    return " ~ ".join(parts) if parts else '""'
