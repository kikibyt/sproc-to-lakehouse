WITH fills AS (
  SELECT
    d.patient_id,
    d.product_id,
    d.dispense_date,
    DATEADD(DAY, d.days_supply, d.dispense_date) AS supply_end_date,
    ROW_NUMBER() OVER (PARTITION BY d.patient_id, d.product_id ORDER BY d.dispense_date, d.dispense_id) AS fill_seq,
    LEAD(d.dispense_date) OVER (PARTITION BY d.patient_id, d.product_id ORDER BY d.dispense_date, d.dispense_id) AS next_dispense_date
  FROM {{ source('dbo', 'dispenses') }} AS d
  WHERE
    d.status = 'DISPENSED' AND d.dispense_date <= CAST({{ sql_literal(var('as_of_date')) }} AS DATE)
), gaps AS (
  SELECT
    patient_id,
    product_id,
    fill_seq,
    dispense_date,
    supply_end_date,
    next_dispense_date,
    DATEDIFF(
      DAY,
      CAST(supply_end_date AS TIMESTAMP),
      CAST(COALESCE(next_dispense_date, CAST({{ sql_literal(var('as_of_date')) }} AS DATE)) AS TIMESTAMP)
    ) AS gap_days
  FROM fills
)
SELECT
  patient_id AS patient_id,
  product_id AS product_id,
  fill_seq AS fill_seq,
  dispense_date AS dispense_date,
  supply_end_date AS supply_end_date,
  next_dispense_date AS next_dispense_date,
  gap_days AS gap_days,
  CASE
    WHEN gap_days <= 0
    THEN 'ON_TIME'
    WHEN gap_days <= CAST({{ sql_literal(var('gap_threshold_days', 7)) }} AS INT)
    THEN 'MINOR_GAP'
    WHEN gap_days <= 30
    THEN 'MAJOR_GAP'
    ELSE 'LAPSED'
  END AS gap_category,
  CAST(CASE WHEN next_dispense_date IS NULL THEN 1 ELSE 0 END AS BOOLEAN) AS is_open_gap,
  CAST('{{ run_started_at.strftime("%Y-%m-%d %H:%M:%S") }}' AS TIMESTAMP) AS calculated_at
FROM gaps
WHERE
  gap_days > 0 OR next_dispense_date IS NULL
