WITH tmp_late(shipment_id, promised_delivery_date, delivered_date, days_late, requires_cold_chain) AS (
  SELECT
    s.shipment_id,
    s.promised_delivery_date,
    CAST(s.delivered_at AS DATE),
    DATEDIFF(
      DAY,
      CAST(s.promised_delivery_date AS TIMESTAMP),
      CAST(COALESCE(CAST(s.delivered_at AS DATE), DATEADD(DAY, 6, CAST({{ sql_literal(var('week_start')) }} AS DATE))) AS TIMESTAMP)
    ),
    s.requires_cold_chain
  FROM {{ source('dbo', 'shipments') }} AS s
  WHERE
    s.shipped_at >= CAST({{ sql_literal(var('week_start')) }} AS DATE)
    AND s.shipped_at < DATEADD(DAY, 7, CAST({{ sql_literal(var('week_start')) }} AS DATE))
    AND (
      s.delivered_at IS NULL OR CAST(s.delivered_at AS DATE) > s.promised_delivery_date
    )
)
SELECT
  EXTRACT(WEEK FROM CAST({{ sql_literal(var('week_start')) }} AS DATE)) AS iso_week,
  st.region_code,
  s.ship_method,
  COUNT(*) AS shipped_count,
  SUM(CASE WHEN l.shipment_id IS NULL THEN 1 ELSE 0 END) AS on_time_count,
  SUM(CASE WHEN l.days_late BETWEEN 1 AND 2 THEN 1 ELSE 0 END) AS late_1_2_days,
  SUM(CASE WHEN l.days_late >= 3 THEN 1 ELSE 0 END) AS late_3_plus_days,
  SUM(CASE WHEN l.requires_cold_chain = TRUE THEN 1 ELSE 0 END) AS cold_chain_late,
  CAST(100.0 * SUM(CASE WHEN l.shipment_id IS NULL THEN 1 ELSE 0 END) / NULLIF(COUNT(*), 0) AS DECIMAL(5, 2)) AS on_time_pct
FROM {{ source('dbo', 'shipments') }} AS s
INNER JOIN {{ source('dbo', 'sites') }} AS st
  ON st.site_id = s.site_id
LEFT JOIN tmp_late AS l
  ON l.shipment_id = s.shipment_id
WHERE
  s.shipped_at >= CAST({{ sql_literal(var('week_start')) }} AS DATE)
  AND s.shipped_at < DATEADD(DAY, 7, CAST({{ sql_literal(var('week_start')) }} AS DATE))
GROUP BY
  st.region_code,
  s.ship_method
ORDER BY
  st.region_code,
  s.ship_method
