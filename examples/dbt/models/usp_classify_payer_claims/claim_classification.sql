SELECT
  c.claim_id AS claim_id,
  c.dispense_id AS dispense_id,
  CAST(c.submitted_at AS DATE) AS submitted_date,
  py.payer_type AS payer_type,
  CASE
    WHEN py.payer_type = 'CASH'
    THEN 'SELF_PAY'
    WHEN py.payer_type = 'MANUFACTURER_ASSIST'
    THEN 'ASSISTANCE'
    WHEN py.payer_type = 'GOVERNMENT' AND c.plan_type IN ('PART_D', 'MANAGED_GOV')
    THEN 'GOVERNMENT_MANAGED'
    WHEN py.payer_type = 'GOVERNMENT'
    THEN 'GOVERNMENT_OTHER'
    WHEN py.payer_type = 'COMMERCIAL' AND c.plan_type = 'HDHP'
    THEN 'COMMERCIAL_HDHP'
    ELSE 'COMMERCIAL_STANDARD'
  END AS coverage_segment,
  CASE c.response_code
    WHEN 'P'
    THEN CASE WHEN c.paid_amount < c.billed_amount * 0.5 THEN 'PAID_SHORT' ELSE 'PAID' END
    WHEN 'D'
    THEN 'DUPLICATE'
    WHEN 'R'
    THEN CASE
      WHEN c.reject_code IN ('70', '75', '76')
      THEN 'REJECT_COVERAGE'
      WHEN c.reject_code IN ('79', '88')
      THEN 'REJECT_TIMING'
      WHEN c.reject_code IS NULL
      THEN 'REJECT_UNSPECIFIED'
      ELSE 'REJECT_OTHER'
    END
    ELSE 'UNKNOWN'
  END AS claim_outcome,
  CASE
    WHEN c.patient_pay_amount = 0
    THEN 'TIER_0'
    WHEN c.patient_pay_amount <= 10
    THEN 'TIER_1'
    WHEN c.patient_pay_amount <= 50
    THEN 'TIER_2'
    WHEN c.patient_pay_amount <= 250
    THEN 'TIER_3'
    ELSE 'TIER_4'
  END AS copay_tier,
  CASE
    WHEN c.billed_amount > 0
    THEN CAST(c.paid_amount / c.billed_amount AS DECIMAL(9, 4))
  END AS paid_ratio,
  CASE
    WHEN c.response_code = 'R' AND c.reject_code = '75'
    THEN 'HIGH'
    WHEN c.response_code = 'R' AND py.payer_type = 'GOVERNMENT'
    THEN 'HIGH'
    WHEN c.response_code = 'R'
    THEN 'MEDIUM'
    WHEN c.response_code = 'P' AND c.paid_amount < c.billed_amount * 0.5
    THEN 'MEDIUM'
    ELSE 'NONE'
  END AS follow_up_priority,
  CAST(IF(c.patient_pay_amount > 100, 1, 0) AS BOOLEAN) AS high_oop_flag,
  CAST('{{ run_started_at.strftime("%Y-%m-%d %H:%M:%S") }}' AS TIMESTAMP) AS classified_at
FROM {{ source('dbo', 'claims') }} AS c
JOIN {{ source('dbo', 'payers') }} AS py
  ON py.payer_id = c.payer_id
WHERE
  CAST(c.submitted_at AS DATE) BETWEEN CAST({{ sql_literal(var('from_date')) }} AS DATE) AND CAST({{ sql_literal(var('to_date')) }} AS DATE)
